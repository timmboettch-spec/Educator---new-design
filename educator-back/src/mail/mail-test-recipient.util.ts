/**
 * Defense-in-depth against a real incident: tests/api/utils/env.ts's
 * testEmail() generates unique, never-checked addresses as
 * `${local}+<prefix>-<timestamp>@${domain}` (default local@domain:
 * test@curionn.com) purely for account-identity uniqueness, on the
 * documented assumption that the server it's testing against always runs
 * with EMAIL_MODE=skip. That assumption silently broke — Dev's
 * `edu-email-mode` Key Vault secret was set to 'live' — and every API test
 * run fired real ACS sends to these synthetic mailboxes. Confirmed via ACS's
 * own DeliveryStatusUpdate metric (48h): 433 Bounced / 999 total (~56%
 * success rate) — consistent with real delivery attempts against mailboxes
 * that don't exist, since a "+"-tagged sub-address is never actually
 * provisioned. EMAIL_MODE can be misconfigured again the same way, so this
 * check is independent of it.
 *
 * Matches any address on the configured test mailbox's domain (default
 * curionn.com) whose local part (ignoring any "+" tag) doesn't match the
 * test mailbox — a defensive fallback in case a non-tagged curionn.com
 * literal is ever hardcoded in the suite again (all current test literals
 * follow the "test+...@curionn.com" convention and don't hit this branch).
 * "+"-tagged sub-addresses of the test mailbox itself (e.g.
 * test+educator-123@curionn.com, as generated by testEmail()) are NOT
 * synthetic — curionn.com now has a real catch-all mailbox for them, so
 * they're allowed through to the real provider like the bare address.
 */
export function isSyntheticTestRecipient(address: string, testMailbox: string): boolean {
  const [, recipientDomain] = splitAddress(address);
  if (!recipientDomain) return false;

  if (isReservedTestDomain(recipientDomain)) return true;

  const [local, domain] = splitAddress(testMailbox);
  if (!local || !domain) return false;

  const [recipientLocal] = splitAddress(address);
  if (!recipientLocal) return false;
  if (recipientDomain !== domain) return false;

  const recipientBaseLocal = recipientLocal.split('+')[0];
  return recipientBaseLocal !== local;
}

/**
 * RFC 2606 permanently reserves these TLDs (and example.com/.net/.org)
 * specifically so they can never resolve to a real mailbox — used
 * elsewhere in this same test suite (nobody@nowhere.invalid,
 * ghost@nowhere.invalid in auth.negative.spec.ts/auth.smoke.ts,
 * smoke-edu@smoke.test in admin.smoke.ts, admin-smoke@example.com in
 * admin.requests.json). Confirmed live: nobody@nowhere.invalid reached a
 * real ACS send attempt (Suppressed/DnsDomainDoesNotExist) via
 * forgot-password, which doesn't require the account to exist. This check
 * is independent of TEST_EMAIL_ADDRESS's configured domain, so it also
 * covers literals that were never derived from testEmail() in the first
 * place.
 */
function isReservedTestDomain(domain: string): boolean {
  if (domain === 'example.com' || domain === 'example.net' || domain === 'example.org') {
    return true;
  }
  return (
    domain.endsWith('.test') ||
    domain.endsWith('.example') ||
    domain.endsWith('.invalid') ||
    domain.endsWith('.localhost')
  );
}

function splitAddress(address: string): [string, string] {
  const at = address.indexOf('@');
  if (at < 0) return ['', ''];
  return [address.slice(0, at).toLowerCase(), address.slice(at + 1).toLowerCase()];
}
