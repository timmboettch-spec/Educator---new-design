// One-off script: converts the Carlito WOFF2 files bundled by @fontsource/carlito
// into raw TTF (sfnt), base64-encodes them, and writes src/lib/carlitoFonts.ts
// for embedding into jsPDF (which only accepts TTF/OTF, not WOFF2).
const fs = require('fs');
const path = require('path');
const woff2 = require('wawoff2');

const FILES_DIR = path.join(
  __dirname,
  '..',
  'node_modules',
  '@fontsource',
  'carlito',
  'files'
);
const OUT_FILE = path.join(__dirname, '..', 'src', 'lib', 'carlitoFonts.ts');

const VARIANTS = [
  { key: 'regular', file: 'carlito-latin-400-normal.woff2' },
  { key: 'bold', file: 'carlito-latin-700-normal.woff2' },
  { key: 'italic', file: 'carlito-latin-400-italic.woff2' },
  { key: 'boldItalic', file: 'carlito-latin-700-italic.woff2' },
];

async function main() {
  const entries = [];
  for (const { key, file } of VARIANTS) {
    const woff2Buffer = fs.readFileSync(path.join(FILES_DIR, file));
    const ttfBuffer = await woff2.decompress(woff2Buffer);
    entries.push(`  ${key}: "${Buffer.from(ttfBuffer).toString('base64')}",`);
  }

  const contents = `// Auto-generated by scripts/generate-carlito-fonts.cjs — do not edit by hand.
// Carlito is a metric-compatible, open-license (SIL OFL-1.1) substitute for Calibri.
export const CARLITO_FONTS = {
${entries.join('\n')}
} as const;
`;
  fs.writeFileSync(OUT_FILE, contents, 'utf8');
  console.log(`Wrote ${OUT_FILE}`);
}

main();
